"""Задача 1. Надрукувати рядок у зворотному порядку.

Розв'язок рекурсивний, без жодного циклу.
"""


def print_reversed(s: str) -> None:
    """Друкує рядок s у зворотному порядку, наприклад "tiger" -> "regit"."""
    # Базовий випадок: рядок закінчився - переходимо на новий рядок
    if s == "":
        print()
        return
    # Спочатку друкуємо останній символ...
    print(s[-1], end="")
    # ...а потім рекурсивно - решту рядка без цього символу
    print_reversed(s[:-1])

"""Задача 5. Власна функція піднесення до степеня pow(x, n).

Швидке піднесення до степеня: x^n = (x^(n/2))^2 для парного n
і x^n = (x^(n/2))^2 * x для непарного. Глибина рекурсії - близько log2(n),
тому навіть n = 2^31 обчислюється за ~32 виклики. Без жодного циклу
і без вбудованих pow() та **.
"""


def my_pow(x: float, n: int) -> float:
    """Повертає x у степені n (n - ціле, може бути від'ємним)."""
    # Базовий випадок: будь-яке число в нульовому степені дорівнює 1
    if n == 0:
        return 1.0
    # Від'ємний степінь: x^(-n) = 1 / x^n
    if n < 0:
        return 1 / my_pow(x, -n)
    half = my_pow(x, n // 2)
    if n % 2 == 0:
        return half * half
    return half * half * x

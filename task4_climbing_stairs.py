"""Задача 4. Скільки є способів піднятися на n сходинок кроками по 1 або 2.

На останню сходинку можна потрапити або з (n - 1)-ї (крок 1),
або з (n - 2)-ї (крок 2), тому ways(n) = ways(n - 1) + ways(n - 2).
Розв'язок рекурсивний, без жодного циклу, із запам'ятовуванням (memo),
щоб n = 45 рахувалося миттєво.
"""


def climb_stairs(n: int, memo=None) -> int:
    """Повертає кількість унікальних способів дістатися n-ї сходинки."""
    if memo is None:
        memo = {}
    # Базові випадки: 1 сходинка - 1 спосіб, 2 сходинки - 2 способи
    if n <= 2:
        return n
    if n not in memo:
        memo[n] = climb_stairs(n - 1, memo) + climb_stairs(n - 2, memo)
    return memo[n]

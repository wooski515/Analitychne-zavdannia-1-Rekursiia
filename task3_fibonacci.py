"""Задача 3. Числа Фібоначчі: F(0) = 0, F(1) = 1, F(n) = F(n - 1) + F(n - 2).

Розв'язок рекурсивний, без жодного циклу. Уже обчислені значення
зберігаються у словнику memo, тому кожне F(k) рахується лише один раз.
"""


def fib(n: int, memo=None) -> int:
    """Повертає n-те число Фібоначчі."""
    if memo is None:
        memo = {}
    # Базові випадки: F(0) = 0, F(1) = 1
    if n < 2:
        return n
    if n not in memo:
        memo[n] = fib(n - 1, memo) + fib(n - 2, memo)
    return memo[n]
